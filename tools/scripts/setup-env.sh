#!/usr/bin/env bash
set -euo pipefail

# Colors for output
BLUE='\033[1;34m'
GREEN='\033[1;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

info() { echo -e "${BLUE}ℹ${NC} $1"; }
ok() { echo -e "${GREEN}✓${NC} $1"; }
warn() { echo -e "${YELLOW}⚠${NC} $1"; }

ensure_npmrc() {
    local target="$1"
    mkdir -p "$(dirname "$target")"
    if [ ! -f "$target" ]; then
        cat <<EOF > "$target"
registry=https://registry.npmjs.org
EOF
    elif ! grep -q "registry=https://registry.npmjs.org" "$target"; then
        echo "registry=https://registry.npmjs.org" >> "$target"
    fi
}

info "Checking environment..."

# Remove existing auto-generated config overrides if they exist
if [ -f "uv.toml" ]; then
    rm -f uv.toml
fi
if [ -f "src/rs/.cargo/config.toml" ]; then
    rm -f src/rs/.cargo/config.toml
fi

# Check if running on Rodete (Internal Linux)
if [ -f "/etc/os-release" ] && grep -q "rodete" /etc/os-release; then
    info "Detected Rodete (Internal Linux). Configuring public registries for uv, npm/bun, and cargo..."

    cat <<EOF > uv.toml
# Auto-generated by tools/scripts/setup-env.sh for Rodete compatibility
[[index]]
url = "https://pypi.org/simple"
default = true
EOF
    ok "Created uv.toml with public PyPI index"

    ensure_npmrc ".npmrc"
    ensure_npmrc "src/ts/vertebra-client/.npmrc"
    ok "Configured .npmrc with public npm registry"

    mkdir -p src/rs/.cargo
    cat <<EOF > src/rs/.cargo/config.toml
# Auto-generated by tools/scripts/setup-env.sh for Rodete compatibility
[registries.crates-io]
protocol = "sparse"

[net]
git-fetch-with-cli = true
EOF
    ok "Created src/rs/.cargo/config.toml with sparse crates.io protocol"
else
    info "Standard environment detected. Using default registry configurations."
fi
