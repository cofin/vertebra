"""TypeScript declaration generator for Vertebra procedures."""

import os
import pathlib
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

from vertebra.codegen.ir import AnnotatedType, NamedTypeRef, ObjectType, TypeNode
from vertebra.common.exceptions import TypeGenerationError
from vertebra.core.procedures.registry import ProcedureMetadata

if TYPE_CHECKING:
    from collections.abc import Iterable


@dataclass(slots=True)
class TypeScriptGenerator:
    declared: dict[str, ObjectType] = field(default_factory=dict)
    cyclic_types: set[str] = field(default_factory=set, init=False)

    def generate(self, procedures: "Iterable[ProcedureMetadata]") -> str:
        blocks: list[str] = [
            "// DO NOT EDIT: generated by Vertebra type bridge.",
            "export interface Subscription<T> {",
            "  subscribe(onData: (data: T) => void): () => void;",
            "  [Symbol.asyncIterator](): AsyncIterator<T>;",
            "}",
        ]
        procedures_list = list(procedures)
        for procedure in procedures_list:
            self._collect_named_types(procedure.params.values())
            self._collect_named_types((procedure.return_type,))

        self.cyclic_types = self._detect_cycles()
        for name in self._toposort_named_types():
            obj = self.declared[name]
            blocks.append(self._render_interface(name, obj))

        blocks.append(self._render_procedures_namespace(procedures_list))
        return "\n\n".join(blocks).strip() + "\n"

    def _collect_named_types(self, nodes: "Iterable[TypeNode]") -> None:
        for node in nodes:
            if isinstance(node, ObjectType) and node.name:
                existing = self.declared.get(node.name)
                if existing is None:
                    self.declared[node.name] = node
                elif (
                    existing.fields != node.fields
                    or existing.optional_fields != node.optional_fields
                    or existing.type_params != node.type_params
                    or existing.type_param_constraints != node.type_param_constraints
                ):
                    msg = f"type name collision: {node.name}"
                    raise ValueError(msg)
            for child in node.iter_children():
                self._collect_named_types((child,))

    def _type_ref(self, node: TypeNode) -> str:
        if isinstance(node, ObjectType) and node.name:
            return node.name
        return node.to_typescript()

    def _render_interface(self, name: str, obj: ObjectType) -> str:
        type_params = self._render_type_params(obj.type_params, obj.type_param_constraints)
        kind = "type" if name in self.cyclic_types else "interface"
        head = (
            f"export {kind} {name}{type_params} = {{ "
            if kind == "type"
            else f"export interface {name}{type_params} {{ "
        )
        lines = [head]
        for field_name, field_type in obj.fields.items():
            optional = "?" if field_name in obj.optional_fields else ""
            if isinstance(field_type, AnnotatedType):
                comment = self._format_metadata(field_type.metadata)
                if comment:
                    lines.append(f"  /** {comment} */")
                field_type = field_type.base
            lines.append(f"  {field_name}{optional}: {self._type_ref(field_type)};")
        lines.append("}")
        return "\n".join(lines)

    def _render_type_params(self, params: tuple[str, ...], constraints: dict[str, TypeNode]) -> str:
        if not params:
            return ""
        rendered: list[str] = []
        for name in params:
            constraint = constraints.get(name)
            if constraint is None:
                rendered.append(name)
            else:
                rendered.append(f"{name} extends {self._type_ref(constraint)}")
        return f"<{', '.join(rendered)}>"

    def _render_procedures_namespace(self, procedures: list[ProcedureMetadata]) -> str:
        tree: dict[str, Any] = {}
        for procedure in sorted(procedures, key=lambda item: item.procedure_id):
            parts = procedure.procedure_id.split(".")
            cursor = tree
            for part in parts[:-1]:
                cursor = cursor.setdefault(part, {})
            procs: list[tuple[str, ProcedureMetadata]] = cursor.setdefault("__procedures__", [])
            procs.append((parts[-1], procedure))

        lines: list[str] = ["export namespace Procedures {"]
        self._render_namespace_block(tree, lines, indent="  ")
        lines.append("}")
        return "\n".join(lines)

    def _render_namespace_block(self, tree: dict[str, Any], lines: list[str], *, indent: str) -> None:
        procedures: list[tuple[str, ProcedureMetadata]] = tree.get("__procedures__", [])
        for name, procedure in procedures:
            params_obj = ObjectType(fields=dict(procedure.params))
            signature = f"(params: {self._type_ref(params_obj)}) => Promise<{self._type_ref(procedure.return_type)}>"
            lines.append(f"{indent}export type {name} = {signature};")

        for namespace in sorted(key for key in tree if key != "__procedures__"):
            subtree = tree[namespace]
            lines.append(f"{indent}export namespace {namespace} {{ ")
            self._render_namespace_block(subtree, lines, indent=indent + "  ")
            lines.append(f"{indent}}}")

    def _toposort_named_types(self) -> list[str]:
        graph: dict[str, set[str]] = {}
        for name, obj in self.declared.items():
            deps = set()
            for node in obj.iter_children():
                deps.update(self._named_dependencies(node))
            deps.discard(name)
            graph[name] = deps

        ordered: list[str] = []
        ready = sorted(name for name, deps in graph.items() if not deps)
        while ready:
            name = ready.pop(0)
            ordered.append(name)
            for other, deps in graph.items():
                if name in deps:
                    deps.remove(name)
                    if not deps and other not in ordered and other not in ready:
                        ready.append(other)
                        ready.sort()

        if len(ordered) != len(graph):
            remaining = sorted(name for name in graph if name not in ordered)
            ordered.extend(remaining)
        return ordered

    def _named_dependencies(self, node: TypeNode) -> set[str]:
        deps: set[str] = set()
        if isinstance(node, ObjectType) and node.name:
            deps.add(node.name)
        if isinstance(node, NamedTypeRef):
            deps.add(node.name)
        for child in node.iter_children():
            deps.update(self._named_dependencies(child))
        return deps

    def _detect_cycles(self) -> set[str]:
        graph: dict[str, set[str]] = {}
        for name, obj in self.declared.items():
            deps = set()
            for node in obj.iter_children():
                deps.update(self._named_dependencies(node))
            self_ref = name in deps
            deps.discard(name)
            graph[name] = deps
            if self_ref:
                graph[name].add(name)

        visiting: set[str] = set()
        visited: set[str] = set()
        cyclic: set[str] = set()

        def dfs(node: str) -> None:
            if node in visited:
                return
            if node in visiting:
                cyclic.add(node)
                return
            visiting.add(node)
            for dep in graph.get(node, set()):
                if dep in visiting:
                    cyclic.add(dep)
                    cyclic.add(node)
                else:
                    dfs(dep)
            visiting.remove(node)
            visited.add(node)

        for name in graph:
            dfs(name)

        return cyclic

    def _format_metadata(self, metadata: tuple[object, ...]) -> str:
        if not metadata:
            return ""
        parts = []
        for item in metadata:
            if isinstance(item, str):
                parts.append(item)
            else:
                parts.append(repr(item))
        return "metadata: " + ", ".join(parts)


def validate_typescript(output: str) -> bool:
    """Validate generated TypeScript using an available compiler."""
    command_info = _find_tsc_command()
    if command_info is None:
        return False
    command, cwd = command_info
    tmp_root = _ensure_tmpdir()
    with tempfile.TemporaryDirectory(dir=tmp_root) as tmp:
        types_path = pathlib.Path(tmp) / "types.d.ts"
        index_path = pathlib.Path(tmp) / "index.ts"
        config_path = pathlib.Path(tmp) / "tsconfig.json"
        types_path.write_text(output, encoding="utf-8")
        with index_path.open("w", encoding="utf-8") as handle:
            handle.write('import "./types";\n')
            handle.write("export {};\n")
        config_path.write_text(
            "{\n"
            '  "compilerOptions": {\n'
            '    "strict": true,\n'
            '    "noEmit": true,\n'
            '    "skipLibCheck": true,\n'
            '    "target": "ES2020",\n'
            '    "module": "ESNext",\n'
            '    "moduleResolution": "Bundler"\n'
            "  },\n"
            '  "include": ["index.ts", "types.d.ts"]\n'
            "}\n",
            encoding="utf-8",
        )
        env = os.environ.copy()
        tmp_root_str = str(tmp_root)
        env["TMPDIR"] = tmp_root_str
        env["TEMP"] = tmp_root_str
        env["TMP"] = tmp_root_str
        env["BUN_TMPDIR"] = tmp_root_str
        env["XDG_CACHE_HOME"] = tmp_root_str
        env["npm_config_cache"] = tmp_root_str
        env["NPM_CONFIG_CACHE"] = tmp_root_str
        result = subprocess.run(
            [*command, "--project", str(config_path), "--pretty", "false"],
            capture_output=True,
            text=True,
            env=env,
            cwd=cwd,
            check=False,
        )
        if result.returncode != 0:
            message = result.stderr.strip() or result.stdout.strip()
            if "This is not the tsc command you are looking for" in message:
                return False
            raise TypeGenerationError(message)
    return True


def format_typescript(output: str) -> str:
    """Format TypeScript using prettier if available."""
    command = _find_prettier_command()
    if command is None:
        return output
    result = subprocess.run(
        [*command, "--parser", "typescript"], input=output, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        return output
    return result.stdout


def _find_tsc_command() -> tuple[list[str], pathlib.Path | None] | None:
    repo_root = pathlib.Path(__file__).resolve().parents[4]
    ts_root = repo_root / "src" / "ts"
    if ts_root.exists() and shutil.which("bun") and (ts_root / "node_modules" / "typescript").exists():
        return (["bun", "run", "tsc"], ts_root)
    if shutil.which("tsc"):
        return (["tsc"], None)
    return None


def _find_prettier_command() -> list[str] | None:
    if shutil.which("bunx"):
        return ["bunx", "prettier"]
    if shutil.which("prettier"):
        return ["prettier"]
    return None


def _ensure_tmpdir() -> pathlib.Path:
    candidates = [
        pathlib.Path.cwd() / ".tmp",
        pathlib.Path.cwd() / ".cache" / "vertebra",
        pathlib.Path.home() / ".cache" / "vertebra",
        pathlib.Path(tempfile.gettempdir()),
    ]
    for path in candidates:
        try:
            path.mkdir(parents=True, exist_ok=True)
            test_file = path / ".write-test"
            test_file.write_text("ok", encoding="utf-8")
            test_file.unlink(missing_ok=True)
        except OSError:
            continue
        else:
            return path
    return pathlib.Path(tempfile.gettempdir())
