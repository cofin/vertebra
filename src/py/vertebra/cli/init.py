"""Init command."""

from pathlib import Path

import click

from vertebra.cli.components import console, section_header
from vertebra.cli.theme import COLORS
from vertebra.utils.text import to_identifier


@click.command()
@click.argument("name", required=False)
@click.option(
    "--package-manager",
    type=click.Choice(["uv", "poetry", "hatch", "pdm", "pip"]),
    default="uv",
    help="Package manager to use",
)
def init(name: str | None, package_manager: str) -> None:
    """Initialize a new Vertebra project."""
    if not name:
        name = click.prompt("Project name", default="my-vertebra-app")

    # name is guaranteed to be str after prompt (click.prompt always returns str)
    name = str(name)  # Explicit cast for type checkers
    slug = to_identifier(name)
    project_dir = Path(name)

    if (
        project_dir.exists()
        and any(project_dir.iterdir())
        and not click.confirm(f"Directory {name} is not empty. Continue?", default=False)
    ):
        return

    project_dir.mkdir(exist_ok=True)
    src_dir = project_dir / "src" / "py" / slug
    src_dir.mkdir(parents=True, exist_ok=True)

    # Render templates
    templates_dir = Path(__file__).parent.parent / "templates" / "default"

    context = {"project_name": name, "project_slug": slug}

    # pyproject.toml
    render_template(templates_dir / "pyproject.toml.jinja2", project_dir / "pyproject.toml", context)

    # app.py
    render_template(templates_dir / "app.py.jinja2", src_dir / "app.py", context)

    # __init__.py
    (src_dir / "__init__.py").touch()

    # __main__.py
    with (src_dir / "__main__.py").open("w") as f:
        f.write("from vertebra.cli import main\n\nif __name__ == '__main__':\n    main()\n")

    # README.md
    with (project_dir / "README.md").open("w") as f:
        f.write(
            f"# {name}\n\nGenerated by Vertebra.\n\n## Run\n\n```bash\n{get_run_command(package_manager, slug)}\n```\n"
        )

    console.print()
    console.print(f"[{COLORS['success']}]Successfully initialized {name}![/]")
    console.print()
    section_header("Next Steps")
    console.print(f"  cd {name}")
    console.print(f"  {get_install_command(package_manager)}")
    console.print(f"  {get_run_command(package_manager, slug)}")


def render_template(src: Path, dst: Path, context: dict[str, str]) -> None:
    content = src.read_text()
    for key, value in context.items():
        content = content.replace(f"{{{{ {key} }}}}", value)
    dst.write_text(content)


def get_install_command(pm: str) -> str:
    if pm == "uv":
        return "uv sync"
    if pm == "poetry":
        return "poetry install"
    if pm == "hatch":
        return "hatch env create"
    if pm == "pdm":
        return "pdm install"
    return "pip install -e ."


def get_run_command(pm: str, slug: str) -> str:
    if pm == "uv":
        return f"uv run vertebra serve {slug}.app:app"
    if pm == "poetry":
        return f"poetry run vertebra serve {slug}.app:app"
    if pm == "hatch":
        return f"hatch run vertebra serve {slug}.app:app"
    if pm == "pdm":
        return f"pdm run vertebra serve {slug}.app:app"
    return f"vertebra serve {slug}.app:app"
