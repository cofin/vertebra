"""TypeScript generation for route metadata."""

from typing import TYPE_CHECKING

from vertebra.build.codegen._emitter import SchemaEmitter
from vertebra.build.codegen._ir import AnnotatedType, NamedTypeRef, ObjectType, TypeNode
from vertebra.build.codegen._metadata import RouteMetadata

if TYPE_CHECKING:
    from collections.abc import Iterable

__all__ = ("TypeScriptGenerator", "format_typescript")


class TypeScriptGenerator(SchemaEmitter):
    """Generate TypeScript declarations from collected routes."""

    __slots__ = ()

    def generate(self, routes: "Iterable[RouteMetadata]") -> str:
        """Render TypeScript interfaces and the Procedures namespace."""
        blocks: list[str] = [
            "// DO NOT EDIT: generated by Vertebra route codegen.",
            "export namespace Procedures {",
        ]
        route_list = self._collect_route_objects(routes)

        if self._declared:
            blocks = [
                blocks[0],
                *[self._render_interface(name, obj) for name, obj in self._declared.items()],
                blocks[1],
            ]

        self._render_namespace(route_list, blocks)
        blocks.append("}")
        return "\n\n".join(blocks).strip() + "\n"

    def _render_interface(self, name: str, obj: ObjectType) -> str:
        lines = [f"export interface {name} {{"]
        for field_name, field_type in obj.fields.items():
            optional = "?" if field_name in obj.optional_fields else ""
            if isinstance(field_type, AnnotatedType):
                field_type = field_type.base
            lines.append(f"  {field_name}{optional}: {self._type_ref(field_type)};")
        lines.append("}")
        return "\n".join(lines)

    def _render_namespace(self, routes: list[RouteMetadata], blocks: list[str]) -> None:
        tree: dict[str, object] = {}
        for route in routes:
            parts = route.operation_id.split(".")
            cursor: dict[str, object] = tree
            for part in parts[:-1]:
                child = cursor.setdefault(part, {})
                cursor = child if isinstance(child, dict) else {}
            procedures = cursor.setdefault("__routes__", [])
            if isinstance(procedures, list):
                procedures.append((parts[-1], route))

        self._render_namespace_block(tree, blocks, indent="  ")

    def _render_namespace_block(self, tree: dict[str, object], blocks: list[str], *, indent: str) -> None:
        procedures = tree.get("__routes__", [])
        if isinstance(procedures, list):
            for name, route in procedures:
                params_obj = ObjectType(fields=dict(route.params))
                signature = f"(params: {self._type_ref(params_obj)}) => Promise<{self._type_ref(route.return_type)}>"
                blocks.append(f"{indent}export type {name} = {signature};")

        for namespace in sorted(key for key in tree if key != "__routes__"):
            subtree = tree[namespace]
            if not isinstance(subtree, dict):
                continue
            blocks.append(f"{indent}export namespace {namespace} {{")
            self._render_namespace_block(subtree, blocks, indent=indent + "  ")
            blocks.append(f"{indent}}}")

    def _type_ref(self, node: TypeNode) -> str:
        if isinstance(node, AnnotatedType):
            return self._type_ref(node.base)
        if isinstance(node, ObjectType) and node.name:
            return node.name
        if isinstance(node, NamedTypeRef):
            return node.name
        return node.to_typescript()


def format_typescript(output: str) -> str:
    """Normalize trailing whitespace for generated TypeScript."""
    return "\n".join(line.rstrip() for line in output.strip().splitlines()) + "\n"
