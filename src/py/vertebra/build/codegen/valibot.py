"""Valibot v1 tree-shakeable TypeScript validation schema generator."""

from collections.abc import Iterable, Sequence
from typing import Any

from vertebra.build.codegen._emitter import SchemaEmitter
from vertebra.build.codegen._ir import (
    AnnotatedType,
    ArrayType,
    GenericType,
    LiteralType,
    NamedTypeRef,
    ObjectType,
    PrimitiveType,
    TupleType,
    TypeNode,
    UnionType,
)
from vertebra.build.codegen._json_schema import (
    ParameterResolution,
    json_schema_to_type_node,
    resolve_parameter_node,
)
from vertebra.build.codegen._metadata import RouteMetadata
from vertebra.utils.serializers import encode_json

__all__ = ("ValibotGenerator",)


class ValibotGenerator(SchemaEmitter):
    """Generate Valibot v1 schemas from RouteMetadata, TypeNode IR, or JSON Schema dictionaries."""

    __slots__ = ()

    def generate(self, routes: Iterable[RouteMetadata]) -> str:
        """Render a complete TypeScript module exporting Valibot v1 schemas and InferOutput types."""
        route_list = list(routes)
        resolved_routes: list[tuple[RouteMetadata, list[ParameterResolution]]] = []
        for route in route_list:
            resolutions: list[ParameterResolution] = []
            for param_name, param_node in route.params.items():
                res = resolve_parameter_node(param_name, param_node)
                if not res.include_in_schema:
                    continue
                resolutions.append(res)
                self._collect_objects(res.base_type)
            self._collect_objects(route.return_type)
            resolved_routes.append((route, resolutions))

        lines: list[str] = [
            "// DO NOT EDIT: generated by Vertebra route codegen.",
            "import * as v from 'valibot';",
            "",
        ]

        for name in sorted(self._declared):
            obj = self._declared[name]
            lines.extend(self._render_object_schema(name, obj))
            lines.append(f"export type {name} = v.InferOutput<typeof {name}Schema>;")
            lines.append("")

        for route, resolutions in resolved_routes:
            safe_id = route.operation_id.replace(".", "_")
            param_fields: list[str] = []
            for res in resolutions:
                expr = self._node_to_valibot(res.base_type, res.constraints)
                if not res.required:
                    expr = f"v.optional({expr})"
                prop_key = res.external_name if res.external_name.isidentifier() else encode_json(res.external_name)
                param_fields.append(f"{prop_key}: {expr}")
            lines.append(f"export const {safe_id}Params = v.object({{{', '.join(param_fields)}}});")
            lines.append(f"export const {safe_id}Response = {self._node_to_valibot(route.return_type, ())};")
            lines.append("")

        return "\n".join(lines).strip() + "\n"

    def emit_schema(self, name: str, schema: TypeNode | dict[str, Any]) -> str:
        """Render a named Valibot v1 schema from a TypeNode or JSON Schema dictionary."""
        if isinstance(schema, dict):
            defs = schema.get("$defs") or schema.get("definitions") or {}
            if isinstance(defs, dict):
                for def_name, def_schema in defs.items():
                    if isinstance(def_schema, dict):
                        def_node = json_schema_to_type_node(def_schema, name=def_name)
                        if isinstance(def_node, ObjectType):
                            self._declared[def_name] = def_node
            node = json_schema_to_type_node(schema, name=schema.get("title") or name)
            target_name = schema.get("title") or name
        else:
            node = schema
            target_name = name

        self._collect_objects(node)
        lines: list[str] = [
            "// DO NOT EDIT: generated by Vertebra route codegen.",
            "import * as v from 'valibot';",
            "",
        ]
        for declared_name in sorted(self._declared):
            if declared_name == target_name and isinstance(node, ObjectType):
                continue
            lines.extend(self._render_object_schema(declared_name, self._declared[declared_name]))
            lines.append(f"export type {declared_name} = v.InferOutput<typeof {declared_name}Schema>;")
            lines.append("")

        if isinstance(node, ObjectType):
            schema_name = node.name or target_name
            lines.extend(self._render_object_schema(schema_name, node))
            lines.append(f"export type {schema_name} = v.InferOutput<typeof {schema_name}Schema>;")
        else:
            expr = self._node_to_valibot(node)
            lines.append(f"export const {target_name}Schema = {expr};")
            lines.append(f"export type {target_name} = v.InferOutput<typeof {target_name}Schema>;")
        return "\n".join(lines).strip() + "\n"

    def _render_object_schema(self, name: str, obj: ObjectType) -> list[str]:
        lines: list[str] = []
        fields: list[str] = []
        for field_name, field_type in obj.fields.items():
            res = resolve_parameter_node(field_name, field_type)
            expr = self._node_to_valibot(res.base_type, res.constraints)
            if field_name in obj.optional_fields:
                expr = f"v.optional({expr})"
            fields.append(f"  {field_name}: {expr},")
        inner = "\n".join(fields)
        lines.append(f"export const {name}Schema = v.object({{\n{inner}\n}});")
        return lines

    def _node_to_valibot(
        self,
        node: TypeNode,
        extra_constraints: Sequence[tuple[str, object]] = (),
    ) -> str:
        if isinstance(node, AnnotatedType):
            res = resolve_parameter_node("_", node)
            return self._node_to_valibot(res.base_type, (*extra_constraints, *res.constraints))

        if isinstance(node, ObjectType) and node.name and node.name in self._declared or isinstance(node, NamedTypeRef):
            base = f"{node.name}Schema"
        elif isinstance(node, ObjectType):
            inner_fields = []
            for f_name, f_type in node.fields.items():
                f_res = resolve_parameter_node(f_name, f_type)
                f_expr = self._node_to_valibot(f_res.base_type, f_res.constraints)
                if f_name in node.optional_fields:
                    f_expr = f"v.optional({f_expr})"
                inner_fields.append(f"{f_name}: {f_expr}")
            base = f"v.object({{{', '.join(inner_fields)}}})"
        elif isinstance(node, PrimitiveType):
            base = self._primitive_to_valibot(node.kind)
        elif isinstance(node, ArrayType):
            base = f"v.array({self._node_to_valibot(node.item)})"
        elif isinstance(node, TupleType):
            inner = ", ".join(self._node_to_valibot(item) for item in node.items)
            base = f"v.tuple([{inner}])"
        elif isinstance(node, UnionType):
            inner = ", ".join(self._node_to_valibot(variant) for variant in node.variants)
            base = f"v.union([{inner}])"
        elif isinstance(node, LiteralType):
            base = f"v.literal({encode_json(node.value)})"
        elif isinstance(node, GenericType):
            if node.name in {"Set", "ReadonlySet"} and node.params:
                base = f"v.set({self._node_to_valibot(node.params[0])})"
            elif node.name == "Record" and len(node.params) == 2:
                base = f"v.record(v.string(), {self._node_to_valibot(node.params[1])})"
            else:
                base = "v.unknown()"
        else:
            base = "v.unknown()"

        return self._apply_constraints(base, extra_constraints)

    @staticmethod
    def _primitive_to_valibot(kind: str) -> str:
        mapping = {
            "string": "v.string()",
            "number": "v.number()",
            "boolean": "v.boolean()",
            "null": "v.null()",
            "Uint8Array": "v.instance(Uint8Array)",
        }
        return mapping.get(kind, "v.unknown()")

    @staticmethod
    def _apply_constraints(base: str, constraints: Sequence[tuple[str, object]]) -> str:
        if not constraints:
            return base
        pipes: list[str] = [base]
        for key, value in constraints:
            if key in {"ge", "gt"}:
                pipes.append(f"v.minValue({encode_json(value)})")
            elif key in {"le", "lt"}:
                pipes.append(f"v.maxValue({encode_json(value)})")
            elif key == "multiple_of":
                pipes.append(f"v.multipleOf({encode_json(value)})")
            elif key == "min_length":
                pipes.append(f"v.minLength({encode_json(value)})")
            elif key == "max_length":
                pipes.append(f"v.maxLength({encode_json(value)})")
            elif key == "pattern":
                escaped = str(value).replace("\\", "\\\\").replace("/", "\\/")
                pipes.append(f"v.regex(/{escaped}/)")
        return f"v.pipe({', '.join(pipes)})"
