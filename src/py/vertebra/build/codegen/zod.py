"""Zod TypeScript validation schema generator with Litestar v2/v3 marker and JSON Schema support."""

from collections.abc import Iterable, Sequence
from typing import Any

from vertebra.build.codegen._ir import (
    AnnotatedType,
    ArrayType,
    GenericType,
    LiteralType,
    NamedTypeRef,
    ObjectType,
    PrimitiveType,
    TupleType,
    TypeNode,
    UnionType,
)
from vertebra.build.codegen._metadata import RouteMetadata
from vertebra.build.codegen.procedures import (
    ParameterResolution,
    json_schema_to_type_node,
    resolve_parameter_node,
)
from vertebra.utils.serializers import encode_json

__all__ = ("ZodGenerator",)


class ZodGenerator:
    """Generate Zod schemas from RouteMetadata, TypeNode IR, or JSON Schema dictionaries."""

    __slots__ = ("declared",)

    def __init__(self, declared: dict[str, ObjectType] | None = None) -> None:
        self.declared: dict[str, ObjectType] = declared if declared is not None else {}

    def generate(self, routes: Iterable[RouteMetadata] | dict[str, Any] | TypeNode) -> str:
        """Render a complete TypeScript module exporting Zod schemas."""
        if isinstance(routes, dict):
            return self.generate_from_schema(routes)
        if isinstance(routes, TypeNode):
            return self.generate_from_node(routes)

        route_list = list(routes)
        resolved_routes: list[tuple[RouteMetadata, list[ParameterResolution]]] = []
        for route in route_list:
            resolutions: list[ParameterResolution] = []
            for param_name, param_node in route.params.items():
                res = resolve_parameter_node(param_name, param_node)
                if not res.include_in_schema:
                    continue
                resolutions.append(res)
                self._collect_named_types((res.base_type,))
            self._collect_named_types((route.return_type,))
            resolved_routes.append((route, resolutions))

        lines: list[str] = [
            "// DO NOT EDIT: generated by Vertebra route codegen.",
            'import { z } from "zod";',
            "",
        ]

        for name in sorted(self.declared):
            lines.append(f"export const {name}Schema = {self._render_object(self.declared[name])};")
            lines.append(f"export type {name} = z.infer<typeof {name}Schema>;")
            lines.append("")

        for route, resolutions in resolved_routes:
            safe_id = route.operation_id.replace(".", "_")
            fields: list[str] = []
            for res in resolutions:
                expr = self._node_to_zod(res.base_type, res.constraints)
                if not res.required:
                    expr = f"{expr}.optional()"
                prop_key = res.external_name if res.external_name.isidentifier() else encode_json(res.external_name)
                fields.append(f"{prop_key}: {expr}")
            lines.append(f"export const {safe_id}Params = z.object({{{', '.join(fields)}}});")
            lines.append(f"export const {safe_id}Response = {self._node_to_zod(route.return_type, ())};")
            lines.append("")

        return "\n".join(lines).strip() + "\n"

    def generate_from_node(self, node: TypeNode, *, name: str = "Value") -> str:
        """Render a Zod schema module from a single TypeNode IR root."""
        self._collect_named_types((node,))
        lines: list[str] = [
            "// DO NOT EDIT: generated by Vertebra route codegen.",
            'import { z } from "zod";',
            "",
        ]
        for declared_name in sorted(self.declared):
            if declared_name == name and isinstance(node, ObjectType):
                continue
            lines.append(f"export const {declared_name}Schema = {self._render_object(self.declared[declared_name])};")
            lines.append(f"export type {declared_name} = z.infer<typeof {declared_name}Schema>;")
            lines.append("")

        if isinstance(node, ObjectType):
            schema_name = node.name or name
            lines.append(f"export const {schema_name}Schema = {self._render_object(node)};")
            lines.append(f"export type {schema_name} = z.infer<typeof {schema_name}Schema>;")
        else:
            expr = self._node_to_zod(node)
            lines.append(f"export const {name}Schema = {expr};")
            lines.append(f"export type {name} = z.infer<typeof {name}Schema>;")
        return "\n".join(lines).strip() + "\n"

    def generate_from_schema(self, schema: dict[str, Any], *, name: str = "Value") -> str:
        """Render a Zod schema module from a JSON Schema dictionary."""
        defs = schema.get("$defs") or schema.get("definitions") or {}
        if isinstance(defs, dict):
            for def_name, def_schema in defs.items():
                if isinstance(def_schema, dict):
                    def_node = json_schema_to_type_node(def_schema, name=def_name)
                    if isinstance(def_node, ObjectType):
                        self.declared[def_name] = def_node
        root_node = json_schema_to_type_node(schema, name=schema.get("title") or name)
        return self.generate_from_node(root_node, name=schema.get("title") or name)

    def emit_schema(self, name: str, schema: TypeNode | dict[str, Any]) -> str:
        """Render a named Zod schema from a TypeNode or JSON Schema dictionary."""
        if isinstance(schema, dict):
            return self.generate_from_schema(schema, name=name)
        return self.generate_from_node(schema, name=name)

    def _collect_named_types(self, nodes: Iterable[TypeNode]) -> None:
        for node in nodes:
            if isinstance(node, ObjectType) and node.name:
                self.declared.setdefault(node.name, node)
            for child in node.iter_children():
                self._collect_named_types((child,))

    def _render_object(self, obj: ObjectType) -> str:
        fields: list[str] = []
        for field_name, field_type in obj.fields.items():
            res = resolve_parameter_node(field_name, field_type)
            expr = self._node_to_zod(res.base_type, res.constraints)
            if field_name in obj.optional_fields:
                expr = f"{expr}.optional()"
            fields.append(f"{field_name}: {expr}")
        return f"z.object({{{', '.join(fields)}}})"

    def _node_to_zod(
        self,
        node: TypeNode,
        extra_constraints: Sequence[tuple[str, object]] = (),
    ) -> str:
        if isinstance(node, AnnotatedType):
            res = resolve_parameter_node("_", node)
            return self._node_to_zod(res.base_type, (*extra_constraints, *res.constraints))

        if isinstance(node, ObjectType) and node.name and node.name in self.declared or isinstance(node, NamedTypeRef):
            base = f"{node.name}Schema"
        elif isinstance(node, ObjectType):
            base = self._render_object(node)
        elif isinstance(node, PrimitiveType):
            base = self._primitive_to_zod(node.kind)
        elif isinstance(node, ArrayType):
            base = f"z.array({self._node_to_zod(node.item)})"
        elif isinstance(node, TupleType):
            inner = ", ".join(self._node_to_zod(item) for item in node.items)
            base = f"z.tuple([{inner}])"
        elif isinstance(node, UnionType):
            inner = ", ".join(self._node_to_zod(variant) for variant in node.variants)
            base = f"z.union([{inner}])"
        elif isinstance(node, LiteralType):
            base = f"z.literal({encode_json(node.value)})"
        elif isinstance(node, GenericType):
            if node.name in {"Set", "ReadonlySet"} and node.params:
                base = f"z.set({self._node_to_zod(node.params[0])})"
            elif node.name == "Record" and len(node.params) == 2:
                base = f"z.record({self._node_to_zod(node.params[1])})"
            else:
                base = "z.unknown()"
        else:
            base = "z.unknown()"

        return self._apply_constraints(base, extra_constraints)

    @staticmethod
    def _primitive_to_zod(kind: str) -> str:
        mapping = {
            "string": "z.string()",
            "number": "z.number()",
            "boolean": "z.boolean()",
            "null": "z.null()",
            "Uint8Array": "z.instanceof(Uint8Array)",
        }
        return mapping.get(kind, "z.unknown()")

    @staticmethod
    def _apply_constraints(base: str, constraints: Sequence[tuple[str, object]]) -> str:
        result = base
        for key, value in constraints:
            if key == "ge":
                result += f".gte({encode_json(value)})"
            elif key == "gt":
                result += f".gt({encode_json(value)})"
            elif key == "le":
                result += f".lte({encode_json(value)})"
            elif key == "lt":
                result += f".lt({encode_json(value)})"
            elif key == "multiple_of":
                result += f".multipleOf({encode_json(value)})"
            elif key == "min_length":
                result += f".min({encode_json(value)})"
            elif key == "max_length":
                result += f".max({encode_json(value)})"
            elif key == "pattern":
                escaped = str(value).replace("\\", "\\\\").replace("/", "\\/")
                result += f".regex(/{escaped}/)"
        return result
