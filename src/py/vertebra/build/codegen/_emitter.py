"""Shared SchemaEmitter base class for schema and client generators."""

from collections.abc import Iterable, Sequence
from typing import TYPE_CHECKING, Any, ClassVar

from vertebra.build.codegen._ir import (
    AnnotatedType,
    ArrayType,
    GenericType,
    LiteralType,
    NamedTypeRef,
    ObjectType,
    PrimitiveType,
    TupleType,
    TypeNode,
    UnionType,
)
from vertebra.build.codegen._json_schema import (
    ParameterResolution,
    json_schema_to_type_node,
    resolve_parameter_node,
)
from vertebra.utils.serializers import encode_json

if TYPE_CHECKING:
    from vertebra.build.codegen._metadata import RouteMetadata

__all__ = ("SchemaEmitter", "_BaseValidatorEmitter")


class SchemaEmitter:
    """Base schema emitter tracking declared named object types across routes and IR trees."""

    __slots__ = ("_declared",)

    def __init__(self, declared: dict[str, ObjectType] | None = None) -> None:
        """Initialize the emitter with optional pre-declared types."""
        self._declared: dict[str, ObjectType] = declared if declared is not None else {}

    @property
    def declared(self) -> dict[str, ObjectType]:
        """Return the dictionary of declared named ObjectType instances."""
        return self._declared

    @declared.setter
    def declared(self, value: dict[str, ObjectType]) -> None:
        """Set the dictionary of declared named ObjectType instances."""
        self._declared = value

    def reset(self) -> None:
        """Clear all declared named types."""
        self._declared.clear()

    def _collect_objects(self, node: TypeNode) -> None:
        """Recursively collect named ObjectType instances from a TypeNode IR subtree."""
        if isinstance(node, ObjectType) and node.name:
            self._declared.setdefault(node.name, node)
        for child in node.iter_children():
            self._collect_objects(child)

    def _collect_named_types(self, nodes: Iterable[TypeNode]) -> None:
        """Collect named ObjectType instances across an iterable of TypeNodes."""
        for node in nodes:
            self._collect_objects(node)

    def _collect_route_objects(self, routes: Iterable["RouteMetadata"]) -> list["RouteMetadata"]:
        """Collect named objects across route parameters and return types, returning routes as a list."""
        route_list = list(routes)
        for route in route_list:
            for param_name, param_node in route.params.items():
                resolution = resolve_parameter_node(param_name, param_node)
                if not resolution.include_in_schema:
                    continue
                self._collect_objects(resolution.base_type)
            self._collect_objects(route.return_type)
            if route.receive_schema is not None:
                self._collect_objects(route.receive_schema)
            if route.send_schema is not None:
                self._collect_objects(route.send_schema)
        return route_list


class _BaseValidatorEmitter(SchemaEmitter):
    """Shared TypeScript schema validator generator base used by Zod and Valibot emitters."""

    __slots__ = ()

    _import_line: ClassVar[str]
    _prefix: ClassVar[str]
    _infer_type: ClassVar[str]
    _uint8_expr: ClassVar[str]

    def generate(self, routes: Iterable["RouteMetadata"]) -> str:
        """Render a complete TypeScript module exporting validation schemas."""
        resolved_routes: list[tuple[RouteMetadata, list[ParameterResolution]]] = []
        for route in routes:
            resolutions: list[ParameterResolution] = []
            for param_name, param_node in route.params.items():
                res = resolve_parameter_node(param_name, param_node)
                if not res.include_in_schema:
                    continue
                resolutions.append(res)
                self._collect_objects(res.base_type)
            self._collect_objects(route.return_type)
            resolved_routes.append((route, resolutions))

        lines = ["// DO NOT EDIT: generated by Vertebra route codegen.", self._import_line, ""]
        for name in sorted(self._declared):
            lines.extend(self._emit_object_decl(name, self._declared[name]))
            lines.append(self._emit_type_alias(name))
            lines.append("")

        for route, resolutions in resolved_routes:
            safe_id = route.operation_id.replace(".", "_")
            fields: list[str] = []
            for res in resolutions:
                expr = self._node_to_expr(res.base_type, res.constraints)
                if not res.required:
                    expr = self._wrap_optional(expr)
                prop_key = res.external_name if res.external_name.isidentifier() else encode_json(res.external_name)
                fields.append(f"{prop_key}: {expr}")
            lines.append(f"export const {safe_id}Params = {self._prefix}.object({{{', '.join(fields)}}});")
            lines.append(f"export const {safe_id}Response = {self._node_to_expr(route.return_type, ())};")
            lines.append("")
        return "\n".join(lines).strip() + "\n"

    def emit_schema(self, name: str, schema: TypeNode | dict[str, Any]) -> str:
        """Render a named validation schema from a TypeNode or JSON Schema dictionary."""
        if isinstance(schema, dict):
            defs = schema.get("$defs") or schema.get("definitions") or {}
            if isinstance(defs, dict):
                for def_name, def_schema in defs.items():
                    if isinstance(def_schema, dict):
                        def_node = json_schema_to_type_node(def_schema, name=def_name)
                        if isinstance(def_node, ObjectType):
                            self._declared[def_name] = def_node
            node = json_schema_to_type_node(schema, name=schema.get("title") or name)
            target_name = schema.get("title") or name
        else:
            node = schema
            target_name = name

        self._collect_objects(node)
        lines = ["// DO NOT EDIT: generated by Vertebra route codegen.", self._import_line, ""]
        for declared_name in sorted(self._declared):
            if declared_name == target_name and isinstance(node, ObjectType):
                continue
            lines.extend(self._emit_object_decl(declared_name, self._declared[declared_name]))
            lines.append(self._emit_type_alias(declared_name))
            lines.append("")

        if isinstance(node, ObjectType):
            schema_name = node.name or target_name
            lines.extend(self._emit_object_decl(schema_name, node))
            lines.append(self._emit_type_alias(schema_name))
        else:
            lines.append(f"export const {target_name}Schema = {self._node_to_expr(node)};")
            lines.append(self._emit_type_alias(target_name))
        return "\n".join(lines).strip() + "\n"

    def _emit_type_alias(self, name: str) -> str:
        return f"export type {name} = {self._infer_type}<typeof {name}Schema>;"

    def _emit_object_decl(self, name: str, obj: ObjectType) -> list[str]:
        return [f"export const {name}Schema = {self._render_inline_object(obj)};"]

    def _render_inline_object(self, obj: ObjectType) -> str:
        fields: list[str] = []
        for field_name, field_type in obj.fields.items():
            res = resolve_parameter_node(field_name, field_type)
            expr = self._node_to_expr(res.base_type, res.constraints)
            if field_name in obj.optional_fields:
                expr = self._wrap_optional(expr)
            fields.append(f"{field_name}: {expr}")
        return f"{self._prefix}.object({{{', '.join(fields)}}})"

    def _node_to_expr(self, node: TypeNode, extra_constraints: Sequence[tuple[str, object]] = ()) -> str:
        p = self._prefix
        if isinstance(node, AnnotatedType):
            res = resolve_parameter_node("_", node)
            return self._node_to_expr(res.base_type, (*extra_constraints, *res.constraints))
        if (isinstance(node, ObjectType) and node.name and node.name in self._declared) or isinstance(
            node, NamedTypeRef
        ):
            base = f"{node.name}Schema"
        elif isinstance(node, ObjectType):
            base = self._render_inline_object(node)
        elif isinstance(node, PrimitiveType):
            base = {
                "string": f"{p}.string()",
                "number": f"{p}.number()",
                "boolean": f"{p}.boolean()",
                "null": f"{p}.null()",
                "Uint8Array": self._uint8_expr,
            }.get(node.kind, f"{p}.unknown()")
        elif isinstance(node, ArrayType):
            base = f"{p}.array({self._node_to_expr(node.item)})"
        elif isinstance(node, TupleType):
            base = f"{p}.tuple([{', '.join(self._node_to_expr(item) for item in node.items)}])"
        elif isinstance(node, UnionType):
            base = f"{p}.union([{', '.join(self._node_to_expr(variant) for variant in node.variants)}])"
        elif isinstance(node, LiteralType):
            base = f"{p}.literal({encode_json(node.value)})"
        elif isinstance(node, GenericType):
            if node.name in {"Set", "ReadonlySet"} and node.params:
                base = f"{p}.set({self._node_to_expr(node.params[0])})"
            elif node.name == "Record" and len(node.params) == 2:
                base = self._render_record(self._node_to_expr(node.params[1]))
            else:
                base = f"{p}.unknown()"
        else:
            base = f"{p}.unknown()"
        return self._apply_constraints(base, extra_constraints)

    def _wrap_optional(self, expr: str) -> str:
        raise NotImplementedError

    def _render_record(self, value_expr: str) -> str:
        raise NotImplementedError

    def _apply_constraints(self, base: str, constraints: Sequence[tuple[str, object]]) -> str:
        raise NotImplementedError
