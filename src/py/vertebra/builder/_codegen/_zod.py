"""Zod generation for route metadata."""

from dataclasses import dataclass, field
from typing import TYPE_CHECKING

from vertebra.builder._codegen._ir import (
    AnnotatedType,
    ArrayType,
    GenericType,
    LiteralType,
    NamedTypeRef,
    ObjectType,
    PrimitiveType,
    RawType,
    StreamType,
    TupleType,
    TypeNode,
    UnionType,
    UnknownType,
)
from vertebra.builder._codegen._metadata import RouteMetadata

if TYPE_CHECKING:
    from collections.abc import Iterable


@dataclass(slots=True)
class ZodGenerator:
    """Generate Zod schemas from collected routes."""

    declared: dict[str, ObjectType] = field(default_factory=dict)

    def generate(self, routes: "Iterable[RouteMetadata]") -> str:
        route_list = list(routes)
        for route in route_list:
            self._collect_named_types(route.params.values())
            self._collect_named_types((route.return_type,))

        lines = [
            "// DO NOT EDIT: generated by Vertebra route codegen.",
            'import { z } from "zod";',
            "",
        ]

        for name, obj in self.declared.items():
            lines.append(self._render_object_schema(name, obj))
            lines.append("")

        for route in route_list:
            safe_id = route.operation_id.replace(".", "_")
            params_obj = ObjectType(fields=dict(route.params))
            lines.append(f"export const {safe_id}Params = {self._node_to_zod(params_obj)};")
            lines.append(f"export const {safe_id}Response = {self._node_to_zod(route.return_type)};")
            lines.append("")

        return "\n".join(lines).strip() + "\n"

    def _collect_named_types(self, nodes: "Iterable[TypeNode]") -> None:
        for node in nodes:
            if isinstance(node, ObjectType) and node.name:
                self.declared.setdefault(node.name, node)
            for child in node.iter_children():
                self._collect_named_types((child,))

    def _render_object_schema(self, name: str, obj: ObjectType) -> str:
        return f"export const {name}Schema = {self._node_to_zod(obj)};"

    def _node_to_zod(self, node: TypeNode) -> str:  # noqa: PLR0911
        if isinstance(node, AnnotatedType):
            return self._node_to_zod(node.base)
        if isinstance(node, ArrayType):
            return f"z.array({self._node_to_zod(node.item)})"
        if isinstance(node, GenericType):
            if node.name == "Set" and node.params:
                return f"z.set({self._node_to_zod(node.params[0])})"
            if node.name == "Record" and len(node.params) == 2:
                return f"z.record({self._node_to_zod(node.params[1])})"
            return "z.unknown()"
        if isinstance(node, LiteralType):
            return f"z.literal({node.to_typescript()})"
        if isinstance(node, NamedTypeRef):
            return f"{node.name}Schema"
        if isinstance(node, ObjectType):
            if node.name and node.name in self.declared:
                fields = ", ".join(
                    f"{field}: {self._maybe_optional(field, field_type, node.optional_fields)}"
                    for field, field_type in node.fields.items()
                )
                return f"z.object({{{fields}}})"
            fields = ", ".join(
                f"{field}: {self._maybe_optional(field, field_type, node.optional_fields)}"
                for field, field_type in node.fields.items()
            )
            return f"z.object({{{fields}}})"
        if isinstance(node, PrimitiveType):
            return self._primitive_to_zod(node)
        if isinstance(node, RawType | StreamType | UnknownType):
            return "z.unknown()"
        if isinstance(node, TupleType):
            inner = ", ".join(self._node_to_zod(item) for item in node.items)
            return f"z.tuple([{inner}])"
        if isinstance(node, UnionType):
            inner = ", ".join(self._node_to_zod(variant) for variant in node.variants)
            return f"z.union([{inner}])"
        return "z.unknown()"

    def _maybe_optional(self, field: str, node: TypeNode, optional_fields: set[str]) -> str:
        rendered = self._node_to_zod(node)
        if field in optional_fields:
            return f"{rendered}.optional()"
        return rendered

    def _primitive_to_zod(self, node: PrimitiveType) -> str:
        if node.kind == "string":
            return "z.string()"
        if node.kind == "number":
            return "z.number()"
        if node.kind == "boolean":
            return "z.boolean()"
        if node.kind == "null":
            return "z.null()"
        if node.kind == "Uint8Array":
            return "z.instanceof(Uint8Array)"
        return "z.unknown()"


__all__ = ("ZodGenerator",)
