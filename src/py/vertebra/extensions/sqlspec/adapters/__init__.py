def __getattr__(name: str) -> Any:
    """Resolve adapter configurations, drivers, stores, and helpers lazily via PEP 562."""
    module_name = _EXPORT_MAP.get(name)
    if module_name is None:
        msg = f"module {__name__!r} has no attribute {name!r}"
        raise AttributeError(msg)
    value = getattr(ensure_module(module_name), name)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    """Return all lazily exported adapter symbol names."""
    return sorted(__all__)
