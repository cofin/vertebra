"""Valibot v1 tree-shakeable TypeScript validation schema generator."""

import json
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field

from vertebra.builder._codegen._ir import (
    AnnotatedType,
    ArrayType,
    GenericType,
    LiteralType,
    NamedTypeRef,
    ObjectType,
    PrimitiveType,
    TupleType,
    TypeNode,
    UnionType,
)
from vertebra.builder._codegen._metadata import RouteMetadata
from vertebra.extensions.codegen.procedures import ParameterResolution, resolve_parameter_node

__all__ = ("ValibotGenerator",)


@dataclass(slots=True)
class ValibotGenerator:
    """Generate Valibot v1 schemas from RouteMetadata with Litestar v2/v3 marker awareness."""

    declared: dict[str, ObjectType] = field(default_factory=dict)

    def generate(self, routes: Iterable[RouteMetadata]) -> str:
        """Render a complete TypeScript module exporting Valibot v1 schemas and InferOutput types."""
        route_list = list(routes)
        resolved_routes: list[tuple[RouteMetadata, list[ParameterResolution]]] = []
        for route in route_list:
            resolutions: list[ParameterResolution] = []
            for param_name, param_node in route.params.items():
                res = resolve_parameter_node(param_name, param_node)
                if not res.include_in_schema:
                    continue
                resolutions.append(res)
                self._collect_named_types((res.base_type,))
            self._collect_named_types((route.return_type,))
            resolved_routes.append((route, resolutions))

        lines: list[str] = [
            "// DO NOT EDIT: generated by Vertebra route codegen.",
            "import * as v from 'valibot';",
            "",
        ]

        for name in sorted(self.declared):
            obj = self.declared[name]
            lines.extend(self._render_object_schema(name, obj))
            lines.append(f"export type {name} = v.InferOutput<typeof {name}Schema>;")
            lines.append("")

        for route, resolutions in resolved_routes:
            safe_id = route.operation_id.replace(".", "_")
            param_fields: list[str] = []
            for res in resolutions:
                expr = self._node_to_valibot(res.base_type, res.constraints)
                if not res.required:
                    expr = f"v.optional({expr})"
                prop_key = res.external_name if res.external_name.isidentifier() else json.dumps(res.external_name)
                param_fields.append(f"{prop_key}: {expr}")
            lines.append(f"export const {safe_id}Params = v.object({{{', '.join(param_fields)}}});")
            lines.append(f"export const {safe_id}Response = {self._node_to_valibot(route.return_type, ())};")
            lines.append("")

        return "\n".join(lines).strip() + "\n"

    def _collect_named_types(self, nodes: Iterable[TypeNode]) -> None:
        for node in nodes:
            if isinstance(node, ObjectType) and node.name:
                self.declared.setdefault(node.name, node)
            for child in node.iter_children():
                self._collect_named_types((child,))

    def _render_object_schema(self, name: str, obj: ObjectType) -> list[str]:
        lines = [f"export const {name}Schema = v.object({{"]
        for field_name, field_type in obj.fields.items():
            res = resolve_parameter_node(field_name, field_type)
            expr = self._node_to_valibot(res.base_type, res.constraints)
            if field_name in obj.optional_fields:
                expr = f"v.optional({expr})"
            lines.append(f"  {field_name}: {expr},")
        lines.append("});")
        return lines

    def _node_to_valibot(
        self,
        node: TypeNode,
        extra_constraints: Sequence[tuple[str, object]] = (),
    ) -> str:
        if isinstance(node, AnnotatedType):
            res = resolve_parameter_node("_", node)
            return self._node_to_valibot(res.base_type, (*extra_constraints, *res.constraints))

        if isinstance(node, ObjectType) and node.name and node.name in self.declared:
            base_expr = f"{node.name}Schema"
        elif isinstance(node, NamedTypeRef):
            base_expr = f"v.lazy(() => {node.name}Schema)"
        elif isinstance(node, PrimitiveType):
            base_expr = self._primitive_to_valibot(node.kind)
        elif isinstance(node, ArrayType):
            base_expr = f"v.array({self._node_to_valibot(node.item)})"
        elif isinstance(node, TupleType):
            items = ", ".join(self._node_to_valibot(item) for item in node.items)
            base_expr = f"v.tuple([{items}])"
        elif isinstance(node, UnionType):
            variants = [self._node_to_valibot(variant) for variant in node.variants]
            base_expr = variants[0] if len(variants) == 1 else f"v.union([{', '.join(variants)}])"
        elif isinstance(node, LiteralType):
            base_expr = f"v.literal({json.dumps(node.value)})"
        elif isinstance(node, ObjectType):
            fields: list[str] = []
            for f_name, f_type in node.fields.items():
                f_res = resolve_parameter_node(f_name, f_type)
                f_expr = self._node_to_valibot(f_res.base_type, f_res.constraints)
                if f_name in node.optional_fields:
                    f_expr = f"v.optional({f_expr})"
                fields.append(f"{f_name}: {f_expr}")
            base_expr = f"v.object({{{', '.join(fields)}}})"
        elif isinstance(node, GenericType):
            if node.name in {"Set", "ReadonlySet"} and len(node.params) == 1:
                base_expr = f"v.set({self._node_to_valibot(node.params[0])})"
            elif node.name == "Record" and len(node.params) == 2:
                k_expr = self._node_to_valibot(node.params[0])
                v_expr = self._node_to_valibot(node.params[1])
                base_expr = f"v.record({k_expr}, {v_expr})"
            else:
                base_expr = "v.unknown()"
        else:
            base_expr = "v.unknown()"

        pipes = self._format_constraints(extra_constraints)
        if pipes:
            return f"v.pipe({', '.join([base_expr, *pipes])})"
        return base_expr

    @staticmethod
    def _primitive_to_valibot(kind: str) -> str:
        mapping = {
            "string": "v.string()",
            "number": "v.number()",
            "boolean": "v.boolean()",
            "null": "v.null_()",
            "Uint8Array": "v.instance(Uint8Array)",
            "any": "v.any()",
        }
        return mapping.get(kind, "v.unknown()")

    @staticmethod
    def _format_constraints(constraints: Sequence[tuple[str, object]]) -> list[str]:
        pipes: list[str] = []
        for key, value in constraints:
            if key == "ge":
                pipes.append(f"v.minValue({json.dumps(value)})")
            elif key == "gt":
                pipes.append(f"v.minValue({json.dumps(value)}, {{ exclusive: true }})")
            elif key == "le":
                pipes.append(f"v.maxValue({json.dumps(value)})")
            elif key == "lt":
                pipes.append(f"v.maxValue({json.dumps(value)}, {{ exclusive: true }})")
            elif key == "multiple_of":
                pipes.append(f"v.multipleOf({json.dumps(value)})")
            elif key == "min_length":
                pipes.append(f"v.minLength({json.dumps(value)})")
            elif key == "max_length":
                pipes.append(f"v.maxLength({json.dumps(value)})")
            elif key == "pattern":
                escaped = str(value).replace("\\", "\\\\").replace("/", "\\/")
                pipes.append(f"v.regex(/{escaped}/)")
        return pipes
