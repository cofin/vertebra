"""Oracle APEX 24.2+ ApexLang compiler and Git-native CI/CD export runner."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

__all__ = (
    "ApexExportArtifact",
    "ApexLangRunner",
)


@dataclass(frozen=True, slots=True)
class ApexExportArtifact:
    """Generated SQL/YAML artifact from an ApexLang compilation or APEX export."""

    app_id: int
    source_path: Path
    output_sql: str


class ApexLangRunner:
    """Compiles declarative ``.apexlang`` specifications into APEX/ORDS SQL installation scripts."""

    def __init__(self, workspace_name: str = "VERTEBRA_WS") -> None:
        self.workspace_name = workspace_name

    def compile_spec(
        self,
        app_id: int,
        source_path: str | Path,
        spec_source: str,
    ) -> ApexExportArtifact:
        """Compile an ``.apexlang`` specification into an idempotent APEX/ORDS SQL script."""
        resolved_path = Path(source_path)
        sanitized_ws = self.workspace_name.replace("'", "''")
        sql_lines = [
            f"-- Generated by Vertebra ApexLangRunner for application {app_id}",
            "BEGIN",
            f"    APEX_APPLICATION_INSTALL.SET_WORKSPACE('{sanitized_ws}');",
            f"    APEX_APPLICATION_INSTALL.SET_APPLICATION_ID({int(app_id)});",
            f"    -- Source: {resolved_path.name} ({len(spec_source.splitlines())} lines)",
            "END;",
            "/",
        ]
        return ApexExportArtifact(
            app_id=app_id,
            source_path=resolved_path,
            output_sql="\n".join(sql_lines),
        )
